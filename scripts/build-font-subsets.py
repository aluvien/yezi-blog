#!/usr/bin/env python3
"""Generate checked-in CJK webfonts. Normal builds need no Python dependencies.

Run with fonttools==4.67.0 and brotli==1.2.0. Common characters are ranked by
public word frequencies; Chiron groups partition rare characters. No site
content or database is used.
"""

from copy import deepcopy
from hashlib import sha256
import json
from pathlib import Path
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "public/fonts"
OUTPUT = FONTS / "subsets"
CSS = ROOT / "src/app/whono/styles/fonts.generated.css"
MANIFEST = OUTPUT / "manifest.json"
MAX_CHARACTERS = 192
ORDER = ROOT / "scripts/font-character-order.txt"
SOURCES = [
    ("lxgw-wenkai-lite", "LXGW WenKai Lite", 400),
    ("noto-serif-sc-400", "Noto Serif SC", 400),
    ("noto-serif-sc-600", "Noto Serif SC", 600),
]


def unicode_ranges(text):
    result = set()
    for item in text.split(","):
        bounds = item.strip().removeprefix("U+").removeprefix("u+").split("-")
        result.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    return result


def css_ranges(characters):
    points = sorted(characters)
    ranges = []
    start = end = points[0]
    for point in points[1:]:
        if point == end + 1:
            end = point
        else:
            ranges.append((start, end))
            start = end = point
    ranges.append((start, end))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def in_original_range(point, kind):
    if kind == "common":
        return 0x4E00 <= point <= 0x9FFF
    return 0x3400 <= point <= 0x4DBF or 0x20000 <= point <= 0x2A6DF


def character_groups(characters, reference, kind):
    if kind == "common":
        ranked = [ord(char) for char in ORDER.read_text().strip() if ord(char) in characters]
        ranked.extend(sorted(characters - set(ranked)))
        # Keep frequent text together, but avoid downloading hundreds of rare
        # glyphs when only one is needed. Do not tune this to one site's text.
        offset = 0
        for size in [256, 128, 128, 128, 128]:
            yield set(ranked[offset:offset + size])
            offset += size
        for offset in range(offset, len(ranked), 48):
            yield set(ranked[offset:offset + 48])
        return
    remaining = set(characters)
    for group in [*reference, characters]:
        selected = sorted(remaining & group)
        for offset in range(0, len(selected), MAX_CHARACTERS):
            chunk = set(selected[offset:offset + MAX_CHARACTERS])
            remaining.difference_update(chunk)
            yield chunk
    assert not remaining


def main():
    reference_css = (FONTS / "chiron/css/vf.css").read_text()
    reference = [unicode_ranges(item) for item in re.findall(
        r"unicode-range:\s*([^;]+)", reference_css
    )]
    OUTPUT.mkdir(parents=True, exist_ok=True)
    previous = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    previous_sources = {item["file"]: item["sha256"] for item in previous.get("sources", [])}
    previous_files = {(item["source"], item["unicodeRange"]): item
                      for item in previous.get("files", []) if previous.get("version") == 1}
    rules = ["/* Generated by scripts/build-font-subsets.py. Do not edit by hand. */"]
    manifest = {"version": 1, "sources": [], "files": []}
    expected_files = {"manifest.json"}
    for prefix, family, weight in SOURCES:
        for kind in ["common", "ext"]:
            source = FONTS / f"{prefix}-cjk-{kind}.woff2"
            font = TTFont(source, recalcTimestamp=False)
            characters = {point for point in font.getBestCmap()
                          if in_original_range(point, kind)}
            source_info = {
                "file": source.name, "sha256": sha256(source.read_bytes()).hexdigest(),
                "family": family, "weight": weight, "characters": len(characters),
                "unicodeRange": css_ranges(characters),
            }
            manifest["sources"].append(source_info)
            coverage = set()
            for index, group in enumerate(character_groups(characters, reference, kind)):
                ranges = css_ranges(group)
                cached = previous_files.get((source.name, ranges))
                data = None
                if cached and previous_sources.get(source.name) == source_info["sha256"]:
                    candidate = OUTPUT / cached["file"]
                    if candidate.exists():
                        payload = candidate.read_bytes()
                        digest = sha256(payload).hexdigest()[:12]
                        if candidate.name.endswith(f"-{digest}.woff2"):
                            data = payload
                if data is None:
                    options = subset.Options()
                    options.layout_features = ["*"]
                    options.recalc_timestamp = False
                    options.canonical_order = True
                    # Preserve the original outlines, hinting, and layout features.
                    # Bump manifest version if these generation options change.
                    options.name_IDs = ["*"]
                    result = deepcopy(font)
                    cutter = subset.Subsetter(options=options)
                    cutter.populate(unicodes=group)
                    cutter.subset(result)
                    result.flavor = "woff2"
                    from io import BytesIO
                    buffer = BytesIO()
                    result.save(buffer)
                    data = buffer.getvalue()
                filename = f"{prefix}-{kind}-{index:03d}-{sha256(data).hexdigest()[:12]}.woff2"
                destination = OUTPUT / filename
                destination.write_bytes(data)
                # Check the generated binary, not just the requested subset.
                with TTFont(destination) as generated:
                    assert set(generated.getBestCmap()) == group, filename
                assert not coverage & group, filename
                coverage.update(group)
                expected_files.add(filename)
                rules.append(
                    f'@font-face{{font-family:"{family}";font-style:normal;'
                    f'font-weight:{weight};font-display:swap;'
                    f'src:url("/fonts/subsets/{filename}") format("woff2");'
                    f'unicode-range:{ranges};}}'
                )
                manifest["files"].append({
                    "file": filename, "source": source.name, "bytes": len(data),
                    "characters": len(group), "unicodeRange": ranges,
                })
            assert coverage == characters, source.name
            print(f"{source.name}: {len(characters)} characters, complete coverage", flush=True)
            font.close()
    CSS.write_text("\n".join(rules) + "\n")
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    # Only remove obsolete generated assets; original fonts remain build inputs.
    for path in OUTPUT.glob("*.woff2"):
        if path.name not in expected_files:
            path.unlink()
    print(f"Generated {len(manifest['files'])} subsets; CSS {CSS.stat().st_size} bytes")


if __name__ == "__main__":
    main()
